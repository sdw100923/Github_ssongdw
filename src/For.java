public class For {
    public static void main(String[] args){
        for (int i = 0; i <=5; i++){
            System.out.print("*");
            if (i % 2 ==0){
                System.out.print(" ");
            }
        }System.out.print("\n");
        for (int j = 0; j <=4; j++){
            System.out.print("*");
        }System.out.print("\n");
        for (int k = 0; k <=3; k++){
            System.out.print("*");
        }

    }
}
